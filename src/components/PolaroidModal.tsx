import React, { useState } from 'react'
import { Download, Sparkles, Flame, Check, Share2, X } from 'lucide-react'
import { RoomUpgrade, SessionStats } from '../types'

interface PolaroidModalProps {
  isOpen: boolean
  onClose: () => void
  studioCanvasRef: React.RefObject<HTMLCanvasElement>
  stats: SessionStats
  attachedLeavesCount: number
  fallenLeavesCount: number
  upgrades: RoomUpgrade[]
}

export const PolaroidModal: React.FC<PolaroidModalProps> = ({
  isOpen,
  onClose,
  studioCanvasRef,
  stats,
  attachedLeavesCount,
  fallenLeavesCount,
  upgrades,
}) => {
  const [presetMode, setPresetMode] = useState<'current' | 'good_day' | 'cooked_brain'>('current')
  const [copied, setCopied] = useState(false)

  if (!isOpen) return null

  const isGoodDay =
    presetMode === 'good_day' ||
    (presetMode === 'current' && stats.tabSwitches <= 4 && attachedLeavesCount >= 4)

  const headline = isGoodDay
    ? 'SUNLITBOTANICAL PENTHOUSE // 0 CASUALTIES'
    : 'COOKED BRAIN BIOHAZARD // FROSTBITTEN STUDIO'

  const captionQuote = isGoodDay
    ? `"LOCKED IN ON '${stats.currentTask.toUpperCase()}'. GREW ${
        presetMode === 'good_day' ? 14 : stats.leavesGrown
      } PROCEDURAL LEAVES & UNLOCKED ${
        presetMode === 'good_day' ? 5 : upgrades.filter((u) => u.unlocked).length
      }/5 COZY UPGRADES."`
    : `"SURVIVED ${
        presetMode === 'cooked_brain' ? 34 : Math.max(stats.tabSwitches, 12)
      } TAB SWITCHES & 3 YOUTUBE RABBIT HOLES. SEND HELP."`

  const handleDownloadPolaroid = () => {
    const srcCanvas = studioCanvasRef.current
    if (!srcCanvas) return

    const exportCanvas = document.createElement('canvas')
    exportCanvas.width = 900
    exportCanvas.height = 760
    const ctx = exportCanvas.getContext('2d')
    if (!ctx) return

    // Polaroid vintage cream cardstock background
    ctx.fillStyle = '#faf7f0'
    ctx.fillRect(0, 0, 900, 760)

    // Subtle paper border
    ctx.strokeStyle = '#d6d3d1'
    ctx.lineWidth = 4
    ctx.strokeRect(12, 12, 876, 736)

    // Top Specimen Stamp Header
    ctx.fillStyle = '#1c1917'
    ctx.font = 'bold 15px "JetBrains Mono", monospace'
    ctx.fillText('THE DAILY LEASE INSPECTION // BOTANICAL FOCUS SPECIMEN', 40, 44)

    ctx.fillStyle = isGoodDay ? '#047857' : '#be123c'
    ctx.font = 'bold 14px "JetBrains Mono", monospace'
    ctx.textAlign = 'right'
    ctx.fillText(
      new Date().toLocaleDateString('en-US', {
        month: 'short',
        day: 'numeric',
        year: 'numeric',
      }),
      860,
      44
    )
    ctx.textAlign = 'left'

    // Draw live studio canvas snapshot inside Polaroid frame
    ctx.fillStyle = '#0c0a09'
    ctx.fillRect(38, 60, 824, 484)
    ctx.drawImage(srcCanvas, 40, 62, 820, 480)

    // Stamp Badge over bottom-right corner of photo
    ctx.save()
    ctx.translate(725, 495)
    ctx.rotate(-0.08)
    ctx.fillStyle = isGoodDay ? 'rgba(6, 95, 70, 0.92)' : 'rgba(159, 18, 57, 0.92)'
    ctx.strokeStyle = isGoodDay ? '#34d399' : '#fda4af'
    ctx.lineWidth = 2.5
    ctx.beginPath()
    ctx.roundRect(-110, -24, 220, 48, 8)
    ctx.fill()
    ctx.stroke()
    ctx.fillStyle = '#ffffff'
    ctx.font = 'extrabold 14px "JetBrains Mono", monospace'
    ctx.textAlign = 'center'
    ctx.fillText(isGoodDay ? 'PASSED: THRIVING GREENHOUSE' : 'FAILED: TRASH FIRE', 0, 5)
    ctx.restore()

    // Polaroid Bottom Caption Area
    ctx.fillStyle = '#1c1917'
    ctx.font = 'bold 21px "Playfair Display", Georgia, serif'
    ctx.fillText(headline, 40, 588)

    ctx.fillStyle = isGoodDay ? '#065f46' : '#9f1239'
    ctx.font = 'bold 15px "JetBrains Mono", monospace'
    ctx.fillText(captionQuote, 40, 622)

    // Metrics Strip at bottom of Polaroid
    const metrics = [
      `FOCUS TIME: ${Math.max(1, Math.floor(stats.focusSeconds / 60))} MIN`,
      `TAB SWITCHES: ${presetMode === 'cooked_brain' ? 34 : stats.tabSwitches}`,
      `SURVIVING LEAVES: ${presetMode === 'good_day' ? 14 : attachedLeavesCount}`,
      `FLOOR CORPSES: ${presetMode === 'cooked_brain' ? 11 : fallenLeavesCount}`,
      `GOLDEN LEAVES: ${stats.goldenLeavesPainted}`,
    ]

    ctx.fillStyle = '#44403c'
    ctx.font = 'bold 13px "JetBrains Mono", monospace'
    ctx.fillText(metrics.join('   ·   '), 40, 668)

    // Footer watermark
    ctx.fillStyle = '#78716c'
    ctx.font = '12px "JetBrains Mono", monospace'
    ctx.fillText(
      'Generated by "Leaf Me Alone" — The Melodramatic Focus Roommate & Procedural Plant',
      40,
      715
    )

    const dataUrl = exportCanvas.toDataURL('image/png')
    const link = document.createElement('a')
    link.download = `leaf-me-alone-inspection-${Date.now()}.png`
    link.href = dataUrl
    link.click()
  }

  const handleCopyShareText = () => {
    const text = `${headline}\n${captionQuote}\n🌱 Surviving Leaves: ${attachedLeavesCount} | 💀 Floor Corpses: ${fallenLeavesCount} | 🏆 Golden Leaves: ${stats.goldenLeavesPainted}`
    navigator.clipboard.writeText(text)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  const snapshotDataUrl = studioCanvasRef.current?.toDataURL('image/png')

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 p-4 backdrop-blur-sm">
      <div className="relative w-full max-w-2xl rounded-2xl border border-stone-700 bg-stone-900 p-6 shadow-2xl">
        <div className="mb-4 flex items-center justify-between">
          <div>
            <span className="font-mono text-xs uppercase tracking-widest text-emerald-400">
              Shareable Payoff
            </span>
            <h2 className="font-serif text-2xl font-bold text-stone-100">
              The Daily Lease Inspection Card
            </h2>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg border border-stone-700 p-2 text-stone-400 hover:bg-stone-800 hover:text-stone-100"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Preset Switcher to preview Good Focus Day vs Cooked Brain Day */}
        <div className="mb-4 flex flex-wrap gap-2">
          <button
            onClick={() => setPresetMode('current')}
            className={`rounded-lg px-3 py-1.5 font-mono text-xs font-semibold transition ${
              presetMode === 'current'
                ? 'bg-emerald-600 text-white'
                : 'bg-stone-800 text-stone-300 hover:bg-stone-700'
            }`}
          >
            Live Session Stats
          </button>
          <button
            onClick={() => setPresetMode('good_day')}
            className={`flex items-center gap-1.5 rounded-lg px-3 py-1.5 font-mono text-xs font-semibold transition ${
              presetMode === 'good_day'
                ? 'bg-emerald-600 text-white'
                : 'bg-stone-800 text-stone-300 hover:bg-stone-700'
            }`}
          >
            <Sparkles className="h-3.5 w-3.5" />
            Preview "Good Focus Day"
          </button>
          <button
            onClick={() => setPresetMode('cooked_brain')}
            className={`flex items-center gap-1.5 rounded-lg px-3 py-1.5 font-mono text-xs font-semibold transition ${
              presetMode === 'cooked_brain'
                ? 'bg-rose-600 text-white'
                : 'bg-stone-800 text-stone-300 hover:bg-stone-700'
            }`}
          >
            <Flame className="h-3.5 w-3.5" />
            Preview "Cooked Brain Day"
          </button>
        </div>

        {/* Polaroid Specimen Card Preview */}
        <div className="mx-auto rounded-xl bg-[#faf7f0] p-4 text-stone-900 shadow-xl">
          <div className="mb-2 flex items-center justify-between font-mono text-[11px] font-bold text-stone-600">
            <span>THE DAILY LEASE INSPECTION // SPECIMEN CARD</span>
            <span className={isGoodDay ? 'text-emerald-700' : 'text-rose-700'}>
              {isGoodDay ? 'GRADE: A+ GREENHOUSE' : 'GRADE: F- FROSTBITTEN'}
            </span>
          </div>

          <div className="relative overflow-hidden rounded-lg border-2 border-stone-900 bg-stone-950">
            {snapshotDataUrl && (
              <img
                src={snapshotDataUrl}
                alt="Studio Snapshot"
                className="block h-auto w-full"
              />
            )}
            <div
              className={`absolute bottom-3 right-3 -rotate-3 rounded-md border-2 px-3 py-1 font-mono text-xs font-extrabold text-white shadow-lg ${
                isGoodDay
                  ? 'border-emerald-300 bg-emerald-900/90'
                  : 'border-rose-300 bg-rose-900/90'
              }`}
            >
              {isGoodDay ? '0 BOTANICAL CASUALTIES' : 'SEND HELP // DOOMSCROLLED'}
            </div>
          </div>

          <div className="mt-3 space-y-1.5">
            <h3 className="font-serif text-lg font-extrabold tracking-tight text-stone-900">
              {headline}
            </h3>
            <p
              className={`font-mono text-xs font-bold ${
                isGoodDay ? 'text-emerald-800' : 'text-rose-800'
              }`}
            >
              {captionQuote}
            </p>
            <div className="flex flex-wrap gap-3 pt-1 font-mono text-[11px] font-semibold text-stone-600">
              <span>
                🌱 Surviving Leaves: {presetMode === 'good_day' ? 14 : attachedLeavesCount}
              </span>
              <span>
                💀 Floor Corpses: {presetMode === 'cooked_brain' ? 11 : fallenLeavesCount}
              </span>
              <span>
                🔄 Tab Switches: {presetMode === 'cooked_brain' ? 34 : stats.tabSwitches}
              </span>
              <span>🏆 Golden Leaves: {stats.goldenLeavesPainted}</span>
            </div>
          </div>
        </div>

        {/* Export Actions */}
        <div className="mt-5 flex flex-wrap items-center justify-end gap-3">
          <button
            onClick={handleCopyShareText}
            className="flex items-center gap-2 rounded-xl border border-stone-700 bg-stone-800 px-4 py-2.5 font-mono text-xs font-bold text-stone-200 hover:bg-stone-700"
          >
            {copied ? <Check className="h-4 w-4 text-emerald-400" /> : <Share2 className="h-4 w-4" />}
            {copied ? 'Copied Inspection Report!' : 'Copy Share Caption'}
          </button>
          <button
            onClick={handleDownloadPolaroid}
            className="flex items-center gap-2 rounded-xl bg-emerald-600 px-5 py-2.5 font-mono text-xs font-bold text-white shadow-lg shadow-emerald-950/50 hover:bg-emerald-500"
          >
            <Download className="h-4 w-4" />
            Export PNG Polaroid Card
          </button>
        </div>
      </div>
    </div>
  )
}
